// Same-document routing and ongoing gameplay, against the local company mock only.
const { chromium } = require('playwright');
const { start } = require('./sheetmock');
const assert = require('node:assert/strict');
start(0, async ({srv, db, url}) => {
  let browser, checks = 0;
  const ok = (name, value) => { assert.ok(value, name); checks++; console.log('  ok   ' + name); };
  try {
    browser = await chromium.launch();
    const context = await browser.newContext({reducedMotion:'reduce', viewport:{width:1100,height:800}});
    const page = await context.newPage(), errors = [];
    page.on('pageerror', e => errors.push(e.message));
    let writes = 0, documents = 0;
    page.on('request', r => { if (r.method() === 'POST') writes++; if (r.resourceType() === 'document') documents++; });
    db.players.push({id:'boss',code:'BOSS',name:'Ceiling Inspector',total:99000,played:3600,pace0:'{"30":8500}'});
    db.ledger.push({id:'payment',from:'worker',fromName:'Floor Inspector',to:'boss',amount:125,kind:'cut',level:1,ts:Date.now()});
    await page.goto(url+'index.html?dev&slot=nav#highscores');
    await page.waitForSelector('#ledger-scores tr');
    ok('direct link opens scores without intro, registration or writes', await page.isHidden('#intro') && await page.isHidden('#modal') && writes===0 && await page.evaluate(()=>!MUSTEAT.state.id));
    ok('30 minutes is the default comparison', await page.inputValue('#ledger-scoreMinute')==='30');
    ok('all ledger sections use the shared company data', await page.textContent('#ledger-sumAll')==='₵125' && /Ceiling Inspector/.test(await page.textContent('#ledger-pairs')) && /Floor Inspector/.test(await page.textContent('#ledger-recent')));
    await page.click('#highscoresView p [data-back-game]');
    await page.waitForSelector('#intro:not([hidden])'); await page.click('#intro'); await page.fill('#nm','View Switcher'); await page.click('#go');
    await page.waitForFunction(()=>MUSTEAT.state.id);
    const id=await page.evaluate(()=>{const s=MUSTEAT.state;s.total=30000;s.cash=30000;s.gear={trainers:3};s.portfolioUnlocked=true;s.pace={30:12000};s.nextEvent=Date.now()+1e9;s.crateAt=Date.now()+1e9;s.told={gang:Date.now(),rec:Date.now()};MUSTEAT.save();MUSTEAT.render();return s.id;});
    await page.click('#tabPfB'); await page.locator('.footer-scores').scrollIntoViewIfNeeded();
    const before = await page.evaluate(()=>({scroll:scrollY,cash:MUSTEAT.state.cash})), docs=documents;
    await page.click('.footer-scores'); await page.waitForSelector('#highscoresView:not([hidden])');
    ok('footer switches view without another document or tab', documents===docs && context.pages().length===1 && await page.isHidden('#gameView'));
    await page.waitForFunction(()=>document.activeElement.id==='ledger-heading');
    ok('scores heading receives keyboard focus', await page.evaluate(()=>document.activeElement.id==='ledger-heading'));
    await page.waitForFunction(cash=>MUSTEAT.state.cash>cash,before.cash);
    ok('passive earnings continue with scores open', await page.evaluate(()=>MUSTEAT.state.tab==='portfolio'));
    db.ledger.push({id:'second',from:'worker',to:'boss',amount:75,kind:'royalty',ts:Date.now()});
    await page.evaluate(()=>MUSTEAT.sync());
    ok('normal game sync updates the visible ledger', await page.textContent('#ledger-sumAll')==='₵200' && await page.textContent('#ledger-sumRoy')==='₵75');
    await page.route('**/api?op=sync*', route=>route.fulfill({status:503,body:'Unavailable'}));
    await page.evaluate(()=>MUSTEAT.refreshScores());
    ok('game sync failure preserves the last loaded ledger and offers retry', await page.textContent('#ledger-sumAll')==='₵200' && await page.isVisible('#ledger-retry') && /showing last loaded data/.test(await page.textContent('#ledger-loadMessage')));
    await page.unroute('**/api?op=sync*');
    await page.click('#ledger-retry');await page.waitForFunction(()=>document.getElementById('ledger-retry').hidden);
    ok('retry recovers through the game sync without changing identity', await page.evaluate(who=>MUSTEAT.state.id===who,id));
    await page.click('#highscoresView p [data-back-game]'); await page.waitForSelector('#gameView:not([hidden])');
    await page.waitForFunction(y=>Math.abs(scrollY-y)<2,before.scroll);
    ok('Back to game restores portfolio, scroll and focus', await page.isVisible('#tab-portfolio') && await page.evaluate(()=>document.activeElement.classList.contains('footer-scores')));
    await page.goForward(); await page.waitForSelector('#highscoresView:not([hidden])');
    ok('browser Forward reopens scores', page.url().includes('#highscores'));
    await page.click('[data-order="total"]');
    ok('filter changes update the bookmark URL', page.url().includes('order=total'));
    await page.reload(); await page.waitForSelector('#ledger-scores tr');
    ok('refresh retains view, filter and player identity', await page.locator('[data-order="total"]').evaluate(el=>el.classList.contains('on')) && await page.evaluate(who=>MUSTEAT.state.id===who,id) && await page.isHidden('#modal'));
    await page.goBack(); await page.waitForSelector('#gameView:not([hidden])');
    ok('browser Back returns after filter changes and reload', await page.isVisible('#tab-portfolio'));
    await page.click('#tabRunB'); await page.fill('#scoreMinute','12'); await page.locator('#scoreMinute').press('Tab');
    await page.click('#board a'); await page.waitForSelector('#highscoresView:not([hidden])');
    ok('preview link carries its selected minute', await page.inputValue('#ledger-scoreMinute')==='12');
    await page.click('#ledger-myMinute');
    ok('My minute uses this instance’s saved history', await page.inputValue('#ledger-scoreMinute')==='30');
    await page.setViewportSize({width:360,height:800});
    ok('populated scores and ledger fit mobile with tables scrolling internally', await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:'/private/tmp/musteat-scores-mobile.png',fullPage:true});
    await page.setViewportSize({width:1100,height:800});
    await page.screenshot({path:'/private/tmp/musteat-scores-desktop.png',fullPage:true});
    const legacy=await context.newPage();
    await legacy.goto(url+'ledger.html?dev&slot=nav&minute=30&order=total');await legacy.waitForSelector('#ledger-scores tr');
    ok('legacy links redirect with instance and filters intact',new URL(legacy.url()).pathname==='/index.html' && new URL(legacy.url()).searchParams.get('slot')==='nav' && await legacy.inputValue('#ledger-scoreMinute')==='30' && await legacy.locator('[data-order="total"]').evaluate(el=>el.classList.contains('on')));
    ok('no duplicate element IDs or browser errors', errors.length===0 && await page.evaluate(()=>{const ids=[...document.querySelectorAll('[id]')].map(el=>el.id);return ids.length===new Set(ids).size;}));
    console.log('\n'+checks+' navigation checks passed.');
  } catch(e) {console.error(e);process.exitCode=1;}
  finally {if(browser)await browser.close();srv.close();}
});
